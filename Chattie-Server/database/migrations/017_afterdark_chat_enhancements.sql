BEGIN;

ALTER TABLE ad_messages
    ADD COLUMN IF NOT EXISTS message_kind VARCHAR(30) NOT NULL DEFAULT 'chat',
    ADD COLUMN IF NOT EXISTS call_mode VARCHAR(10),
    ADD COLUMN IF NOT EXISTS reply_to_message_id UUID REFERENCES ad_messages(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS is_pinned BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN IF NOT EXISTS pinned_by UUID REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS pinned_at TIMESTAMP WITH TIME ZONE;

CREATE TABLE IF NOT EXISTS ad_message_reactions (
    message_id UUID NOT NULL REFERENCES ad_messages(id) ON DELETE CASCADE,
    user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    emoji VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (message_id, user_id, emoji)
);

COMMIT;
